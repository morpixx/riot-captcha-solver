"""Camoufox resource tuning, ported from the Node Camoufox booster.

The original was a Node helper for the Camoufox npm package.  Python
cannot share Playwright page objects with Node, so the same three ideas are
implemented natively here:

* Firefox preferences that cut helper processes, caches, telemetry and
  prefetching.  WebGL stays enabled: it is part of the fingerprint that
  Camoufox generates and hCaptcha probes it.
* Request blocking for analytics, images, media and webfonts.  hCaptcha
  hosts are always allowed -- blocking its assets produces a token Riot
  rejects, so the block list is deliberately narrower than the original.
* Humanized cursor movement before the invisible widget is executed.

The fingerprint itself is still generated by Camoufox at launch; nothing in
this module weakens or disables it.
"""

from __future__ import annotations

import logging
import random
import re
import time
from contextlib import suppress
from urllib.parse import urlsplit

log = logging.getLogger("riot.browser.camoufox.boost")

# --------------------------------------------------------------------------- #
# Firefox preferences: less CPU/RAM without a fingerprint downgrade.
# --------------------------------------------------------------------------- #
FIREFOX_PREFS: dict[str, bool | int | str] = {
    # A single content process is enough for one page per browser.
    "dom.ipc.processCount": 1,
    "dom.ipc.processCount.webIsolated": 1,
    "fission.autostart": False,
    "browser.tabs.remote.autostart": True,
    # No telemetry, crash reporting or background update traffic.
    "toolkit.telemetry.enabled": False,
    "toolkit.telemetry.unified": False,
    "datareporting.healthreport.uploadEnabled": False,
    "datareporting.policy.dataSubmissionEnabled": False,
    "app.update.enabled": False,
    "extensions.update.enabled": False,
    "browser.startup.homepage_override.mstone": "ignore",
    "browser.shell.checkDefaultBrowser": False,
    # Keep session history and caches small: one page, then discard.
    "browser.cache.disk.enable": False,
    "browser.cache.memory.capacity": 16384,
    "browser.cache.memory.max_entry_size": 512,
    "browser.sessionstore.interval": 9999999,
    "browser.sessionstore.max_tabs_undo": 0,
    "browser.sessionhistory.max_entries": 2,
    "browser.sessionhistory.max_total_viewers": 0,
    "image.mem.surface_cache.max_size_kb": 8192,
    "image.mem.shared": True,
    # No media pipeline, autoplay, WebRTC or prefetching.
    "media.autoplay.default": 5,
    "media.peerconnection.enabled": False,
    "media.memory_cache_max_size": 8192,
    "media.cache_size": 0,
    "media.rdd-process.enabled": False,
    "network.prefetch-next": False,
    "network.dns.disablePrefetch": True,
    "network.process.enabled": False,
    # Less background work: no safebrowsing, spellcheck, reader mode, prelaunch.
    "browser.safebrowsing.malware.enabled": False,
    "browser.safebrowsing.phishing.enabled": False,
    "layout.spellcheckDefault": 0,
    "reader.parse-on-load.enabled": False,
    "general.smoothScroll": False,
    "browser.tabs.unloadOnLowMemory": True,
    "dom.ipc.processPrelaunch.enabled": False,
    "gfx.font_rendering.fallback.async": False,
}

# --------------------------------------------------------------------------- #
# Network blocking: traffic that never helps the Riot flow.
# --------------------------------------------------------------------------- #
BLOCK_TYPES = frozenset({"image", "media", "font"})
TRACKING_HOSTS = re.compile(
    r"(?:^|\.)(?:google-analytics\.com|googletagmanager\.com|doubleclick\.net|"
    r"datadoghq\.com|segment\.io|sentry\.io|fullstory\.com|hotjar\.com|"
    r"optimizely\.com|osano\.com)$",
    re.IGNORECASE,
)
CAPTCHA_HOSTS = re.compile(r"(?:^|\.)hcaptcha\.com$", re.IGNORECASE)


def should_block_request(request: object) -> bool:
    """Return True when a Playwright request can be aborted safely.

    request is any object with url and resource_type attributes, which keeps
    the decision unit-testable without a browser.
    """
    url = str(getattr(request, "url", "") or "")
    if not url.startswith(("http://", "https://")):
        return False
    hostname = (urlsplit(url).hostname or "").lower()
    if hostname and TRACKING_HOSTS.search(hostname):
        return True
    resource_type = str(getattr(request, "resource_type", "") or "").lower()
    return bool(resource_type in BLOCK_TYPES and not CAPTCHA_HOSTS.search(hostname))


def install_resource_blocking(context, *, debug=None) -> None:
    """Install one context-wide route that aborts blocked requests.

    hCaptcha assets are allowed even when they are images/fonts, otherwise
    the invisible widget can hand back a token that Riot rejects.
    """

    def handler(route) -> None:
        try:
            if should_block_request(route.request):
                route.abort()
            else:
                route.continue_()
        except Exception as exc:  # the page may have closed mid-request
            target = debug or log.debug
            target("request routing failed: %s", exc)
            with suppress(Exception):
                route.continue_()

    context.route("**/*", handler)


# --------------------------------------------------------------------------- #
# Human behaviour: a few mouse moves before the challenge is executed.
# --------------------------------------------------------------------------- #
def humanize_page(page, *, log=None) -> None:
    """Move the cursor and scroll a little, like a person would."""
    debug = getattr(log, "debug", None) or globals()["log"].debug
    try:
        size = page.evaluate("({width: window.innerWidth, height: window.innerHeight})")
        width = int((size or {}).get("width") or 1280)
        height = int((size or {}).get("height") or 800)
        moves = 2 + random.randint(0, 5)
        for _ in range(moves):
            x = 40 + random.random() * max(1, width - 80)
            y = 40 + random.random() * max(1, height - 80)
            page.mouse.move(x, y, steps=3 + random.randint(0, 12))
            time.sleep(random.uniform(0.12, 0.65))
            if random.random() < 0.35:
                delta = random.choice((-1, 1)) * (80 + random.random() * 420)
                page.mouse.wheel(0, delta)
                time.sleep(random.uniform(0.18, 0.45))
        page.wait_for_timeout(random.randint(400, 2200))
    except Exception as exc:
        debug("humanize skipped: %s", exc)


# --------------------------------------------------------------------------- #
# Launch options.  The caller still provides the profile dir and proxy.
# --------------------------------------------------------------------------- #
def camoufox_options(
    *,
    headless: bool | str,
    proxy: dict | None,
    geoip: bool | str,
    humanize: bool = True,
) -> dict:
    """Build the Camoufox launcher arguments used by every session."""
    options = {
        "headless": headless,
        "persistent_context": True,
        "os": "windows",
        "geoip": geoip,
        "block_webrtc": True,
        "humanize": humanize,
        "enable_cache": False,
        "firefox_user_prefs": dict(FIREFOX_PREFS),
        "proxy": proxy or None,
    }
    # uBlock Origin roughly doubles resident memory on this Camoufox build
    # (~1.1 GB vs ~0.55 GB for a blank page).  The route blocker below covers
    # the traffic that matters for Riot, so the extension is not worth it.
    try:
        from camoufox import DefaultAddons

        options["exclude_addons"] = [DefaultAddons.UBO]
    except ImportError:  # pragma: no cover - camoufox is a hard dependency
        pass
    return options


