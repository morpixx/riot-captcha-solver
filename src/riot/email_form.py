"""The Riot email card: fill the address and click SAVE AND VERIFY.

The page's hCaptcha React component executes from a real click, so the
n-token is generated by the same widget/session Riot expects. A token minted
by a separate invisible widget (src/riot/minter.py) is rejected by Riot with
the same HTTP 200 / shouldPoll=false body.
"""

from __future__ import annotations

import time
from contextlib import suppress

from ..security import email_domain

EMAIL_INPUT = '[data-testid="personal-information-card__emailAddress"]'
SAVE_BUTTON = '[data-testid="personal-information-card__saveChanges-btn"]'

SUBMIT_ATTEMPTS = 3


def _wait_for_card(page) -> tuple:
    input_box = page.locator(EMAIL_INPUT)
    save = page.locator(SAVE_BUTTON)
    try:
        input_box.wait_for(state="visible", timeout=20000)
        save.wait_for(state="visible", timeout=20000)
    except Exception as exc:
        raise RuntimeError(f"Riot email card is not available: {exc}") from exc
    if not input_box.is_enabled():
        raise RuntimeError("Riot email field is disabled; the current email cannot be changed")
    # Give the hCaptcha React component time to render. Clicking before the
    # first iframe exists gives the app's "captcha_not_ready" path and no POST.
    with suppress(Exception):
        page.wait_for_selector('iframe[src*="hcaptcha"]', state="attached", timeout=15000)
    return input_box, save


def _fill_email(page, input_box, save, email: str) -> None:
    input_box.click()
    input_box.fill(email)
    deadline = time.monotonic() + 10.0
    while time.monotonic() < deadline and save.is_disabled():
        page.wait_for_timeout(200)
    if save.is_disabled():
        raise RuntimeError("Riot SAVE AND VERIFY button stayed disabled after filling the email")


def _click_save(page, save, *, timeout_ms: int):
    """Click the button and return the email-change POST response."""
    last_error = None
    response = None
    for _attempt in range(SUBMIT_ATTEMPTS):
        if save.is_disabled():
            page.wait_for_timeout(500)
            if save.is_disabled():
                continue
        try:
            with page.expect_response(
                lambda candidate: (
                    "/api/account/v1/user/email" in candidate.url
                    and candidate.request.method == "POST"
                ),
                timeout=min(timeout_ms, 8000),
            ) as response_info:
                save.click()
            response = response_info.value
            break
        except Exception as exc:
            last_error = exc
            page.wait_for_timeout(700)
    if response is None:
        raise RuntimeError(
            "Riot did not submit the email change from the UI "
            "(hCaptcha challenge not completed or page changed): " + str(last_error)
        ) from last_error
    return response


def _response_body(response) -> object:
    try:
        return response.json()
    except Exception:
        try:
            return {"text": response.text()[:300]}
        except Exception:
            return None


def submit_via_ui(page, email: str, *, timeout_ms: int, log=print) -> dict:
    """Fill the email card and submit through Riot's own SAVE AND VERIFY button."""
    input_box, save = _wait_for_card(page)
    _fill_email(page, input_box, save, email)
    log(f"[ui] clicking SAVE AND VERIFY -> domain={email_domain(email)}")

    response = _click_save(page, save, timeout_ms=timeout_ms)
    status = response.status
    body = _response_body(response)
    if status >= 400:
        raise RuntimeError(f"Riot rejected the email change from the UI: {status} {body!r}"[:300])
    return {"status": status, "body": body}
